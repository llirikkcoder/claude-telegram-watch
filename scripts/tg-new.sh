#!/bin/zsh
# Завести ещё один телеграм-канал и получить готовую команду запуска.
#
# ЗАЧЕМ. Каналов на машине может быть сколько угодно: плагин читает каталог из
# TELEGRAM_STATE_DIR, у каждого свой бот, свой токен, свой список доступа. В
# README основного плагина об этом сказано одной строкой-выноской, без примеров,
# и на практике никто её не находит. Мы искали сутки, пока сообщения копились
# в очереди у неподнятого бота.
#
# Без аргументов — показывает, что уже есть, и объясняет, как добавить.
# С именем — заводит каталог и печатает команду запуска.
#
# ТОКЕН СКРИПТ НЕ СПРАШИВАЕТ И НЕ ПРИНИМАЕТ АРГУМЕНТОМ. Аргументы попадают в
# историю оболочки и видны в списке процессов всем пользователям машины. Вписать
# его человек должен сам, в файл с правами 600.

set -u

БАЗА="$HOME/.claude/channels"
ИМЯ="${1:-}"

канал_бот() {
  local t=$(grep -oE '[0-9]{8,}:[A-Za-z0-9_-]+' "$1/.env" 2>/dev/null | head -1)
  [[ -z $t ]] && { print "— токена нет —"; return }
  # Показываем только номер бота: токен целиком в выводе — это утечка доступа.
  print "бот ${t%%:*}"
}

if [[ -z $ИМЯ ]]; then
  print "Каналы на этой машине:"
  print ""
  for d in $БАЗА/*(N/); do
    printf "  %-20s %s\n" "${d:t}" "$(канал_бот $d)"
  done
  print ""
  print "Добавить ещё один:  tg-new.sh <имя>"
  print "Имя — любое короткое слово: по нему называется каталог и запуск."
  exit 0
fi

# Имя идёт в путь и в имя функции оболочки — проверяем, а не надеемся.
if [[ ! $ИМЯ =~ '^[a-z][a-z0-9-]{1,30}$' ]]; then
  print "Имя должно быть латиницей, со строчной буквы: буквы, цифры, дефис."
  print "Например:  tg-new.sh ai-o-dev"
  exit 1
fi

КАТАЛОГ="$БАЗА/$ИМЯ"
if [[ -d $КАТАЛОГ ]]; then
  print "Канал «$ИМЯ» уже есть: $КАТАЛОГ"
  print "$(канал_бот $КАТАЛОГ)"
  exit 1
fi

mkdir -p "$КАТАЛОГ/inbox"
umask 077
print 'TELEGRAM_BOT_TOKEN=' > "$КАТАЛОГ/.env"
chmod 600 "$КАТАЛОГ/.env"

print "Канал «$ИМЯ» заведён: $КАТАЛОГ"
print ""
print "ОСТАЛОСЬ ТРИ ШАГА."
print ""
print "1. Заведите бота у @BotFather и получите токен."
print "   Нового, не переиспользуйте чужой: два канала на один токен начнут"
print "   делить сообщения между собой, и половина будет пропадать."
print ""
print "2. Впишите токен в файл (он уже с правами 600):"
print "   $КАТАЛОГ/.env"
print "   Строка целиком:  TELEGRAM_BOT_TOKEN=123456:AA..."
print ""
print "3. Добавьте запуск в ~/.zshrc:"
print ""
print "$ИМЯ() {"
print "  TELEGRAM_STATE_DIR=\"\$HOME/.claude/channels/$ИМЯ\" \\"
print "    claude --channels plugin:telegram@claude-plugins-official \"\$@\""
print "}"
print ""
print "Потом  source ~/.zshrc  — и канал поднимается командой  $ИМЯ"
print ""
print "ОДНА СЕССИЯ — ОДИН КАНАЛ. Два окна с одним и тем же каналом делят"
print "сообщения между собой: половина уходит туда, где её никто не читает."
