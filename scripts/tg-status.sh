#!/bin/zsh
# Состояние Telegram-бота одной строкой для statusLine.
#
# Бот держит long polling: Telegram отдаёт апдейты ровно одному клиенту.
# Каждая сессия Claude поднимает свой экземпляр, поэтому два открытых окна
# = два поллера = сообщения уходят в случайное из них.
#
# Но одного «процесс жив» мало. Экземпляр принадлежит той сессии, которая
# его подняла, и апдейты попадают именно в неё. Для соседнего окна бот
# работает — только не с ним. Раньше строка показывала в этом случае «tg ✓»,
# и выглядело это так, будто ответы должны приходить сюда, а они уходили в
# другое окно. Поэтому теперь проверяется ещё и принадлежность.
#
# Вызывается на каждую отрисовку строки статуса — только ps и чтение файла,
# никаких обращений к api.telegram.org.

PIDFILE=~/.claude/channels/telegram/bot.pid

pids=(${(f)"$(pgrep -f 'bun server\.ts' 2>/dev/null)"})
n=${#pids[@]}

(( n == 0 )) && { print -n "tg ✗ не запущен"; exit 0 }

if (( n > 1 )); then
  print -n "tg ✗ ${n} инстанса — конфликт"
  exit 0
fi

bot=${pids[1]}

# Зависший экземпляр крутит цикл переподключения и жрёт ядро, но апдейты
# уже не забирает: живой поллер почти всё время спит в ожидании ответа.
cpu=$(ps -o %cpu= -p $bot | tr -d ' ' | cut -d. -f1)
(( ${cpu:-0} > 50 )) && { print -n "tg ✗ завис (${cpu}% CPU)"; exit 0 }

# Ищем сессию Claude, которой принадлежит этот скрипт, и сессию, поднявшую
# бота. Если это разные сессии — канал здесь молчит, что бы ни делал бот.
claude_session_of() {
  local p=$1 cmd
  while [[ -n $p && $p != 1 ]]; do
    cmd=$(ps -o command= -p $p 2>/dev/null)
    [[ $cmd == claude* ]] && { print -- $p; return 0 }
    p=$(ps -o ppid= -p $p 2>/dev/null | tr -d ' ')
  done
  return 1
}

mine=$(claude_session_of $$)
owner=$(claude_session_of $bot)

if [[ -n $mine && -n $owner && $mine != $owner ]]; then
  print -n "tg ⚠ в другой сессии"
  exit 0
fi

if [[ -r $PIDFILE ]]; then
  saved=$(<$PIDFILE)
  [[ $saved != $bot ]] && { print -n "tg ⚠ pid разошёлся"; exit 0 }
fi

print -n "tg ✓"
