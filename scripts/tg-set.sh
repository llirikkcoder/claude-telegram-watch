#!/bin/zsh
# Кто держит Telegram-канал и как забрать его себе.
#
# Канал принадлежит той сессии Claude, которая подняла экземпляр бота:
# long polling Telegram отдаёт апдейты одному клиенту, и это он. Соседнее
# окно при этом молчит, сколько его ни перезапускай.
#
# Без аргументов — показывает владельца так, чтобы его можно было найти
# среди десятков открытых окон: терминал, рабочий каталог, время запуска.
# С --take — снимает чужой экземпляр, освобождая канал для текущей сессии.

set -u

TAKE=0
[[ "${1:-}" == "--take" ]] && TAKE=1

# Поднимаемся по цепочке процессов до ближайшей сессии Claude.
claude_session_of() {
  local p=$1 cmd
  while [[ -n $p && $p != 1 ]]; do
    cmd=$(ps -o command= -p $p 2>/dev/null)
    [[ $cmd == claude* ]] && { print -- $p; return 0 }
    p=$(ps -o ppid= -p $p 2>/dev/null | tr -d ' ')
  done
  return 1
}

# Какой канал обслуживает этот экземпляр.
#
# ЗАЧЕМ. Каналов на машине может быть несколько: плагин читает каталог из
# TELEGRAM_STATE_DIR, и у каждого свой бот, свой токен, свой список доступа.
# Пока скрипт об этом не знал, он отвечал «канал здесь» при мёртвом соседнем
# боте — сообщения копились в очереди у Telegram, а человек искал поломку в
# работающем канале. Сутки поисков 22–23.09.2026 начались ровно с этого.
#
# Переменной нет — значит канал по умолчанию: так устроен сам плагин.
channel_of() {
  local p=$1 dir
  dir=$(ps eww -p $p 2>/dev/null | tr ' ' '\n' | grep '^TELEGRAM_STATE_DIR=' | head -1 | cut -d= -f2-)
  print -- "${dir:-$HOME/.claude/channels/telegram}"
}

describe_session() {
  local s=$1
  local tty=$(ps -o tty= -p $s 2>/dev/null | tr -d ' ')
  local started=$(ps -o lstart= -p $s 2>/dev/null | sed 's/^ *//')
  local cwd=$(lsof -a -p $s -d cwd -Fn 2>/dev/null | grep '^n' | sed 's/^n//' | head -1)
  print "  сессия claude $s"
  [[ -n $tty ]] && print "  терминал:  $tty"
  [[ -n $cwd ]] && print "  каталог:   $cwd"
  [[ -n $started ]] && print "  запущена:  $started"
}

# Каналы, настроенные на машине, но никем не поднятые.
#
# САМЫЙ ДОРОГОЙ СЛУЧАЙ — именно этот. Живой канал виден сразу: сообщения
# приходят. Мёртвый не подаёт признаков вообще: Telegram молча копит апдейты
# в очереди, а человек смотрит на работающий канал и не понимает, почему
# «телеграм не работает». У @ai_o_dev_bot так накопилось шестнадцать.
#
# Канал считается настроенным, если в его каталоге лежит .env с токеном.
молчащие() {
  local занято="$1" d
  for d in $HOME/.claude/channels/*(N/); do
    [[ -f $d/.env ]] || continue
    grep -q 'TELEGRAM_BOT_TOKEN=' $d/.env 2>/dev/null || continue
    [[ " $занято " == *" ${d:t} "* ]] && continue
    print -- "${d:t}"
  done
}

# Два каталога на один токен — готовая поломка.
#
# Если поднять оба, они начнут делить сообщения между собой: Telegram отдаёт
# апдейт одному потребителю. Симптом будет тот же, что при двух сессиях на
# одном канале, но причина спрятана в настройке, а не на виду в списке
# процессов. Проверка дешёвая, поэтому делается всегда.
#
# Сравниваем отпечатки, а не токены: токен в выводе — это утечка доступа.
дубли_токенов() {
  local d t
  for d in $HOME/.claude/channels/*(N/); do
    [[ -f $d/.env ]] || continue
    t=$(grep -oE '[0-9]{8,}:[A-Za-z0-9_-]+' $d/.env 2>/dev/null | head -1)
    [[ -n $t ]] && print -- "${t%%:*} ${d:t}"
  # Имена переменных в awk обязаны быть латиницей: кириллица даёт syntax error.
  done | sort | awk '{ n[$1]++; w[$1] = w[$1] " " $2 }
                      END { for (b in n) if (n[b] > 1) print b ":" w[b] }'
}

mine=$(claude_session_of $$)
pids=(${(f)"$(pgrep -f 'bun server\.ts' 2>/dev/null)"})

if (( ${#pids[@]} == 0 )); then
  print "Канал сейчас никем не занят: ни одного экземпляра бота."
  print ""
  print "Сам он не поднимется: экземпляр запускает MCP-клиент сессии при"
  print "подключении. Чтобы канал заработал здесь — /mcp и переподключить"
  print "telegram, либо перезапустить сессию."
  print ""
  print "Если сессия запущена вообще без канала, нужен ключ:"
  print "  claude --channels plugin:telegram@claude-plugins-official"
  тихие=(${(f)"$(молчащие '')"})
  if (( ${#тихие[@]} > 1 )); then
    print ""
    print "Настроено каналов: ${#тихие[@]} — ${тихие[*]}."
    print "Каждый поднимается своей сессией, см. /tg-new."
  fi
  exit 0
fi

print "Экземпляров бота: ${#pids[@]}"
print ""

owners=()
занятые=()
for b in $pids; do
  o=$(claude_session_of $b)
  owners+=(${o:-0})
  ch=$(channel_of $b); chn=${ch:t}
  занятые+=($chn)
  if [[ -n $o && $o == $mine ]]; then
    print "[$chn] держит ЭТА сессия (бот $b) — сообщения приходят сюда."
  elif [[ -n $o && $o != 0 ]]; then
    print "[$chn] держит ДРУГАЯ сессия (бот $b):"
    describe_session $o
  else
    print "[$chn] бот $b осиротел — окно, поднявшее его, закрыто."
  fi
  print ""
done

дубли=(${(f)"$(дубли_токенов)"})
if (( ${#дубли[@]} )); then
  for пара in $дубли; do
    print "ОДИН БОТ В ДВУХ КАНАЛАХ: ${пара#*:}"
  done
  print "Поднимутся оба — начнут делить сообщения между собой."
  print "Оставьте один каталог, лишний уберите или смените в нём токен."
  print ""
fi

тихие=(${(f)"$(молчащие "${занятые[*]}")"})
if (( ${#тихие[@]} )); then
  print "МОЛЧАТ, хотя настроены: ${тихие[*]}"
  print "Их сообщения копятся в очереди у Telegram и сюда не придут."
  print "Поднять: отдельная сессия с TELEGRAM_STATE_DIR на нужный канал,"
  print "см. /tg-new — он же напишет готовую команду запуска."
  print ""
fi

if (( ! TAKE )); then
  if [[ ${owners[(I)$mine]} -gt 0 ]]; then
    print "Забирать нечего: канал уже здесь."
  else
    print "Чтобы забрать канал себе:  tg-set.sh --take"
    print "В том окне канал после этого замолчит до его перезапуска."
  fi
  exit 0
fi

# --take: снимаем всё, что принадлежит не нам.
killed=0
for i in {1..${#pids[@]}}; do
  b=${pids[$i]}
  o=${owners[$i]}
  [[ $o == $mine ]] && continue

  ppid=$(ps -o ppid= -p $b 2>/dev/null | tr -d ' ')
  kill $b 2>/dev/null
  sleep 1
  kill -0 $b 2>/dev/null && kill -9 $b 2>/dev/null
  # Обёртка bun run иначе останется висеть сиротой.
  if [[ -n ${ppid:-} && $ppid != 1 ]]; then
    ps -o command= -p $ppid 2>/dev/null | grep -q 'bun run' && kill $ppid 2>/dev/null
  fi
  killed=$((killed + 1))
  print "Снят чужой экземпляр (бот $b, сессия ${o:-сирота})"
done

if (( killed == 0 )); then
  print "Ничего снимать не пришлось — канал и так здесь."
  exit 0
fi

print ""
print "Канал освобождён — но сам он сюда не переедет."
print ""
print "Экземпляр бота поднимает MCP-клиент сессии при подключении, а не"
print "команда извне. Проверено: после снятия чужого процесса новый не"
print "появляется ни через минуту, ни позже. Дальше — одно из двух:"
print ""
print "  • в Claude Code выполнить /mcp и переподключить telegram;"
print "  • либо перезапустить эту сессию."
print ""
print "После этого:  tg-status.sh  покажет tg ✓"
